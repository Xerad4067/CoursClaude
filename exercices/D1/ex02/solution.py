# Fichier : types.py
print(type(1500))     # int : nombre entier
print(type(3.5))      # float : nombre à virgule (écrit avec un point)
print(type("taxi"))   # str : texte
print(type(True))     # bool : True ou False (majuscule !)
print(type(None))     # NoneType : le « rien » de Python (nil en Lua)
print(type("42"))     # des chiffres entre guillemets : c'est du texte
print(type(10 / 2))   # la division / donne toujours un float
print(type(10 // 2))  # la division entière // de deux int donne un int
